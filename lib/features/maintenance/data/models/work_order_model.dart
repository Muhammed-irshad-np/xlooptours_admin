      startedBy: json['startedBy'] as String?,
      completedAt: _parseDate(json['completedAt']),
      completedBy: json['completedBy'] as String?,
      invoiceUrls: _stringList(json['invoiceUrls']),
      shopInvoiceNumber: json['shopInvoiceNumber'] as String?,
      holdReason: json['holdReason'] as String?,
      expenseId: json['expenseId'] as String?,
      expenseReferenceNumber: json['expenseReferenceNumber'] as String?,
      fundAccountId: json['fundAccountId'] as String?,
      fundAccountName: json['fundAccountName'] as String?,
