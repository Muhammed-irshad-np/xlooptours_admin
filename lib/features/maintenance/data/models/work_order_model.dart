  factory WorkOrderModel.fromJson(Map<String, dynamic> json) {
    return WorkOrderModel(
      id: json['id'] as String? ?? json['workOrderNumber'] as String? ?? '',
      workOrderNumber: json['workOrderNumber'] as String? ?? '',
      status: WorkOrderStatus.fromName(json['status'] as String?),
      source: WorkOrderSource.fromName(json['source'] as String?),
      priority: WorkOrderPriority.fromName(json['priority'] as String?),
      vehicleId: json['vehicleId'] as String? ?? '',
      vehiclePlate: json['vehiclePlate'] as String? ?? '',
      vehicleName: json['vehicleName'] as String?,
      odometerAtRequest: (json['odometerAtRequest'] as num?)?.toInt(),
      odometerAtService: (json['odometerAtService'] as num?)?.toInt(),
      complaint: json['complaint'] as String? ?? '',
      reportedBy: json['reportedBy'] as String?,
      reportedByUserId: json['reportedByUserId'] as String?,
      reportedByRole: json['reportedByRole'] as String?,
      reportedAt: _parseDate(json['reportedAt']),
      reportedAttachmentUrls: _stringList(json['reportedAttachmentUrls']),
      sourceAlertTypeId: json['sourceAlertTypeId'] as String?,
      lines: (json['lines'] as List<dynamic>?)
              ?.map((e) => _lineFromJson(e as Map<String, dynamic>))
              .toList() ??
          const [],
      shopId: json['shopId'] as String?,
      shopName: json['shopName'] as String?,
      scheduledDate: _parseDate(json['scheduledDate']),
      createdBy: json['createdBy'] as String? ?? '',
      createdByUserId: json['createdByUserId'] as String?,
      createdAt: _parseDate(json['createdAt']) ?? DateTime.now(),
      updatedAt: _parseDate(json['updatedAt']),
      approvedBy: json['approvedBy'] as String?,
      approvedByUserId: json['approvedByUserId'] as String?,
      approvedAt: _parseDate(json['approvedAt']),
      approvedAmount: (json['approvedAmount'] as num?)?.toDouble(),
      rejectionReason: json['rejectionReason'] as String?,
      varianceReason: json['varianceReason'] as String?,
