  // ─── Nested line serialization ─────────────────────────────

  static Map<String, dynamic> _lineToJson(WorkOrderLine l) => {
        'id': l.id,
        'maintenanceTypeId': l.maintenanceTypeId,
        'maintenanceTypeName': l.maintenanceTypeName,
        'customTypeName': l.customTypeName,
        'estimatedCost': l.estimatedCost,
        'actualCost': l.actualCost,
        'partsCost': l.partsCost,
        'laborCost': l.laborCost,
        'partsReplaced': l.partsReplaced,
        'notes': l.notes,
        'completed': l.completed,
        'followUpRequired': l.followUpRequired,
        'followUpReason': l.followUpReason,
        'followUpDate': l.followUpDate?.toIso8601String(),
        'followUpKm': l.followUpKm,
        'targetDueDate': l.targetDueDate?.toIso8601String(),
        'notificationDays': l.notificationDays,
      };

  static WorkOrderLine _lineFromJson(Map<String, dynamic> json) =>
      WorkOrderLine(
        id: json['id'] as String? ?? '',
        maintenanceTypeId: json['maintenanceTypeId'] as String? ?? '',
        maintenanceTypeName: json['maintenanceTypeName'] as String? ?? '',
        customTypeName: json['customTypeName'] as String?,
        estimatedCost: (json['estimatedCost'] as num?)?.toDouble() ?? 0,
        actualCost: (json['actualCost'] as num?)?.toDouble(),
        partsCost: (json['partsCost'] as num?)?.toDouble(),
        laborCost: (json['laborCost'] as num?)?.toDouble(),
        partsReplaced: json['partsReplaced'] as String?,
        notes: json['notes'] as String?,
        completed: json['completed'] as bool? ?? true,
        followUpRequired: json['followUpRequired'] as bool? ?? false,
        followUpReason: json['followUpReason'] as String?,
        followUpDate: _parseDate(json['followUpDate']),
        followUpKm: (json['followUpKm'] as num?)?.toInt(),
        targetDueDate: _parseDate(json['targetDueDate']),
        notificationDays: (json['notificationDays'] as num?)?.toInt(),
      );

  static List<String> _stringList(dynamic value) =>
      (value as List<dynamic>?)?.map((e) => e.toString()).toList() ??
      const <String>[];

  /// Tolerates ISO strings, Firestore Timestamps and DateTime alike — the
  /// same defensive parsing `ExpenseModel` uses.
  static DateTime? _parseDate(dynamic val) {
    if (val == null) return null;
    if (val is DateTime) return val;
    if (val is String) return DateTime.tryParse(val);
    try {
      final dynamic d = val;
      if (d.toDate != null) return d.toDate() as DateTime;
    } catch (_) {}
    return null;
  }
